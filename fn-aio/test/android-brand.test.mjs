import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const base=new URL('../android/app/src/main/',import.meta.url);
test('Android 桌面名称 Agent 与 AI 星芒自适应/主题图标，包名不变以支持覆盖升级',async()=>{
  const manifest=await readFile(new URL('AndroidManifest.xml',base),'utf8');
  const strings=await readFile(new URL('res/values/strings.xml',base),'utf8');
  const glyph=await readFile(new URL('res/drawable/ic_agent_glyph.xml',base),'utf8');
  const adaptive=await readFile(new URL('res/mipmap-anydpi/ic_entry_agent.xml',base),'utf8');
  const themed=await readFile(new URL('res/mipmap-anydpi-v33/ic_entry_agent.xml',base),'utf8');
  const build=await readFile(new URL('../../build.gradle',base),'utf8');
  assert.match(manifest,/android:label="@string\/app_name"/);
  assert.match(strings,/<string name="app_name" translatable="false">Agent<\/string>/);
  assert.match(manifest,/android:icon="@mipmap\/ic_entry_agent"/);
  assert.doesNotMatch(manifest,/ic_launcher/);
  assert.match(glyph,/android:fillColor="#FFFFFF"/);
  assert.match(glyph,/M54,22/);
  assert.match(adaptive,/<adaptive-icon/);
  assert.match(adaptive,/@drawable\/ic_agent_bg/);
  assert.match(adaptive,/@drawable\/ic_agent_glyph/);
  assert.match(themed,/<monochrome android:drawable="@drawable\/ic_agent_glyph"/);
  assert.match(build,/applicationId 'top\.fnaio\.direct'/);
  assert.ok(Number(build.match(/versionCode (\d+)/)?.[1])>=32);
});
